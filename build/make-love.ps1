# build/make-love.ps1 — package the game into dist/space-z.love
# The .love is the universal artifact: runs on desktop LÖVE and the Android
# LÖVE player, and is the input to the Windows/Android bundling scripts.
#
#   pwsh build/make-love.ps1 [-IncludeTests]
#   pwsh build/make-love.ps1 -LoveVersion 11.5 -Out dist/space-z-web.love
#
# -LoveVersion packages the game with its own LOVE_VERSION declaring that version instead of
# the repo's, for a runtime that is not the pinned one. conf.lua reads LOVE_VERSION at
# startup, so this is how a package states what it will really run on. Only the browser
# build uses it (see the exception in LOVE_VERSION); -Out keeps that package from
# replacing the desktop one.
param(
  [switch]$IncludeTests,
  [string]$LoveVersion,
  [string]$Out = "dist/space-z.love"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Push-Location $root
try {
  New-Item -ItemType Directory -Force (Split-Path -Parent (Join-Path $root $Out)) | Out-Null
  # LOVE_VERSION is read by conf.lua at startup, so it ships inside the package
  $items = @("conf.lua", "main.lua", "LOVE_VERSION", "src", "lib")
  if ($IncludeTests) { $items += "tests" }

  $love = Join-Path $root $Out
  $zip = [System.IO.Path]::ChangeExtension($love, ".zip")
  if (Test-Path $zip) { Remove-Item $zip -Force }
  if (Test-Path $love) { Remove-Item $love -Force }

  if ($LoveVersion) {
    # stage a copy whose LOVE_VERSION says what the package will run on
    $stage = Join-Path $root "dist/stage-$([guid]::NewGuid().ToString('N'))"
    New-Item -ItemType Directory -Force $stage | Out-Null
    try {
      foreach ($item in $items) { Copy-Item $item $stage -Recurse }
      Set-Content (Join-Path $stage "LOVE_VERSION") -NoNewline -Value (
        "# generated by build/make-love.ps1 -LoveVersion: this package runs on a different LÖVE than the repo pins`nlove=$LoveVersion`n")
      Push-Location $stage
      try { Compress-Archive -Path $items -DestinationPath $zip -Force } finally { Pop-Location }
    } finally {
      Remove-Item $stage -Recurse -Force -ErrorAction SilentlyContinue
    }
  } else {
    Compress-Archive -Path $items -DestinationPath $zip -Force
  }
  Rename-Item $zip (Split-Path -Leaf $love)
  $size = [math]::Round((Get-Item $love).Length / 1KB)
  Write-Host "OK: $Out ($size KB)$(if ($LoveVersion) { " declaring LÖVE $LoveVersion" })"
} finally {
  Pop-Location
}
